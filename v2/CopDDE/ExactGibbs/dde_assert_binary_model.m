function [N,J,K1,K2] = dde_assert_binary_model(A1,A2,Z,B1,B2,gamma,prop)
%DDE_ASSERT_BINARY_MODEL Validate the two-layer Gaussian/logistic DDE model.
% Binary state matrices exclude intercept columns; loading matrices include them.
N = size(Z,1);
J = size(Z,2);
K1 = size(A1,2);
K2 = size(A2,2);
assert(ismatrix(Z) && all(isfinite(Z(:))), 'DDE:InvalidZ', ...
    'Z must be a finite N-by-J matrix.');
assert(ismatrix(A1) && size(A1,1)==N && all(A1(:)==0 | A1(:)==1), ...
    'DDE:InvalidA1', 'A1 must be a binary N-by-K1 matrix without an intercept.');
assert(ismatrix(A2) && size(A2,1)==N && all(A2(:)==0 | A2(:)==1), ...
    'DDE:InvalidA2', 'A2 must be a binary N-by-K2 matrix without an intercept.');
assert(isequal(size(B1),[J,K1+1]) && all(isfinite(B1(:))), ...
    'DDE:InvalidB1', 'B1 must be finite J-by-(K1+1), including the intercept.');
assert(isequal(size(B2),[K1,K2+1]) && all(isfinite(B2(:))), ...
    'DDE:InvalidB2', 'B2 must be finite K1-by-(K2+1), including the intercept.');
assert(numel(gamma)==J && all(isfinite(gamma(:))) && all(gamma(:)>0), ...
    'DDE:InvalidGamma', 'gamma must contain J finite positive variances.');
assert(numel(prop)==K2 && all(isfinite(prop(:))) && ...
    all(prop(:)>=0 & prop(:)<=1), 'DDE:InvalidProp', ...
    'prop must contain K2 probabilities in [0,1].');
end
