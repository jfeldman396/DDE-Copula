function [model,audit,full_selected]=cpdde_export(raw,training_audit,marginals,sources)
% Copy-prune CSP-inactive columns, then remove mathematically unused nodes.
full_selected=r1tune_selected_model(raw);B1=full_selected.B1;B2=full_selected.B2;
first=any(B1(:,2:end)~=0,1);upper=any(B2(:,2:end)~=0,1);
path_upper=any(B2(first,2:end)~=0,1);widths=[sum(first),sum(upper)];J=size(B1,1);
eligible=widths(1)>0&&J>=3*widths(1)&&widths(1)>=3*widths(2)&&isequal(upper,path_upper);
model=struct('B1',B1(:,[1,find(first)+1]),'B2',B2(first,[1,find(upper)+1]), ...
 'gamma',full_selected.gamma(:),'prop',reshape(full_selected.prop(upper),1,[]), ...
 'item_ids',{training_audit.item_ids},'native_first_layer_ids',find(first), ...
 'native_top_layer_ids',find(upper),'widths',widths, ...
 'trained_depth',training_audit.training_depth,'selected_depth',1+(widths(2)>0), ...
 'eligible',eligible,'training_identity',training_audit.training_identity, ...
 'training_row_ids',training_audit.row_ids,'split_id',training_audit.split_id, ...
 'cfg',raw.tuning_config,'marginals',{marginals},'sources',sources, ...
 'fit_seed',raw.seed,'initialization_seed',training_audit.initialization_seed, ...
 'iterations',raw.iteration,'stabilized',raw.stabilized,'kernel','Gibbs_Z');
if training_audit.training_depth==1,assert(size(raw.A2,2)==0&&size(raw.B2,2)==1&&isempty(raw.prop)&&widths(2)==0);end
raw_widths=[sum(any(raw.B1(:,2:end)~=0,1)),sum(any(raw.B2(:,2:end)~=0,1))];
flags=0;maxKKT=0;flagIterations=0;
for it=1:numel(raw.trace)
 t=raw.trace{it};flags=flags+t.flags;flagIterations=flagIterations+(t.flags>0);maxKKT=max(maxKKT,t.KKT);
end
audit=struct('eligible',eligible,'requested_training_depth',training_audit.training_depth, ...
 'actual_widths',widths,'CSP_widths',[sum(raw.active1),sum(raw.active2)], ...
 'raw_nonzero_widths',raw_widths,'path_widths',[sum(first),sum(path_upper)], ...
 'degenerate_K1_zero',widths(1)==0,'reduced_one_layer',widths(1)>0&&widths(2)==0, ...
 'training_identity',training_audit.training_identity,'fit_seed',raw.seed, ...
 'fit_iterations',raw.iteration,'stabilized',raw.stabilized,'CPU',raw.CPU,'wall',raw.wall, ...
 'warm_CPU',raw.warm_CPU,'warm_wall',raw.warm_wall,'CM_flags',flags, ...
 'iterations_with_CM_flags',flagIterations,'maximum_scaled_KKT',maxKKT, ...
 'first_layer_loading_nnz',nnz(model.B1(:,2:end)), ...
 'parameter_fingerprint',cpdde_digest({model.B1,model.B2,model.gamma,model.prop}), ...
 'marginals_are_training_only',true,'no_forced_widths',true, ...
 'width_path_gate_is_not_graphical_identifiability_proof',true);
end
