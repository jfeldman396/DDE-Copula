function t=dc_trace(f,it,beta,lambda,s1,s2,a1,a2,stats,truth)
% Evaluation-only copies apply the existing end-of-fit pruning convention.
score=struct('B1',f.B1,'B2',f.B2,'gamma',f.gamma,'prop',f.prop,'Z',f.Z,'active1',a1,'active2',a2);
score.B1(:,find(~a1)+1)=0; score.B2(:,find(~a2)+1)=0;
m=evaluate_exact_gibbs_fit(score,truth);
t=struct('iteration',it,'beta',beta,'lambda',lambda,'active1',a1,'active2',a2, ...
    'theta2',f.theta2(1,:),'categories2',s2.categories,'loading_mass',sum(abs(f.B2(:,2:end)),1), ...
    'loading_norm',sqrt(sum(f.B2(:,2:end).^2,1)),'csp_state1',s1,'csp_state2',s2, ...
    'metrics',m,'B1',f.B1,'B2',f.B2,'gamma',f.gamma,'prop',f.prop, ...
    'top_seconds',stats.top_conditional_seconds,'iteration_seconds',f.diagnostics.iteration_seconds(it));
end
